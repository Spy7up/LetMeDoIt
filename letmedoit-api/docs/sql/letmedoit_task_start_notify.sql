-- ============================================================
-- 「让我做」开始时间点 + 到点通知开关
-- 项目：smart-admin（MySQL 8.x）
--
-- 背景：
--   原来的「定时生效」只是到点把任务从预约中转到待接受，不通知任何人。
--   产品改成「开始时间点」：到点可以给参与者发一条通知，由委托人开关控制。
-- 默认 1（发通知）：符合「到点就发送通知」的默认预期，老数据保持原行为即可。
-- ============================================================

ALTER TABLE `t_task`
  ADD COLUMN `start_notify_flag` TINYINT(1) NOT NULL DEFAULT 1
  COMMENT '开始时间点到点是否通知参与者 0否 1是' AFTER `start_time`;
